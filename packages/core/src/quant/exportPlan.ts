// Export a mixed-precision plan from a QuantAnalysis: JSON, an ONNX Runtime
// `quantize_static` script (nodes_to_exclude), and a TFLite selective-
// quantization script (QuantizationDebugger denylisted_nodes). Pure, no React.

import type { Model } from "@modelvisio/parsers";
import { DISCLAIMER, REC_LABEL, type QuantAnalysis } from "./sensitivity";

function baseName(model: Model): string {
  return (model.name || "model").replace(/\.[^.]+$/, "") || "model";
}

function inputInfo(model: Model): { name: string; shape: number[] } {
  const io = model.layers.find((l) => /\b(input|placeholder)\b/i.test(`${l.op} ${l.type}`));
  const shape = (model.inputShape.length ? model.inputShape : io?.outs[0]?.s ?? [1]).map((d) => (d > 0 ? d : 1));
  return { name: io?.outs[0]?.n || io?.name || "input", shape };
}

const pyStr = (s: string) => JSON.stringify(s); // JSON string literals are valid Python literals
const pyList = (xs: string[], indent = "    ") =>
  xs.length ? `[\n${xs.map((x) => `${indent}${pyStr(x)},`).join("\n")}\n]` : "[]";

export type PlanJson = {
  model: string;
  format: string;
  generatedBy: string;
  target: string;
  disclaimer: string;
  summary: {
    totalParams: number;
    sizeBytes: QuantAnalysis["summary"]["sizeBytes"];
    safeInt8Pct: number;
    safeInt4Pct: number;
    statsCoverage: number;
    confidence: string;
  };
  nodesToExclude: string[];
  perChannel: string[];
  layers: {
    id: number; name: string; op: string; tensor: string | null; precision: string;
    int8Risk: number; int4Risk: number; int8SqnrDb: number | null; reason: string;
  }[];
};

/** The plan as a plain object (quantizable layers only). */
export function planToJson(model: Model, a: QuantAnalysis): PlanJson {
  const s = a.summary;
  const tensorOf = new Map(model.layers.map((l) => [l.id, l.outs[0]?.n ?? null]));
  return {
    model: model.name,
    format: model.format,
    generatedBy: "ModelVisio quantization heatmap",
    target: s.target,
    disclaimer: DISCLAIMER,
    summary: {
      totalParams: s.totalParams,
      sizeBytes: s.sizeBytes,
      safeInt8Pct: s.safeInt8Pct,
      safeInt4Pct: s.safeInt4Pct,
      statsCoverage: Math.round(s.statsCoverage * 1000) / 1000,
      confidence: s.confidence,
    },
    nodesToExclude: s.excluded.map((l) => l.name),
    perChannel: s.perChannel.map((l) => l.name),
    layers: a.layers.filter((l) => l.quantizable).map((l) => ({
      id: l.id, name: l.name, op: l.op, tensor: tensorOf.get(l.id) ?? null,
      precision: l.recommendation,
      int8Risk: l.int8.perChannelRisk, int4Risk: l.int4.perChannelRisk,
      int8SqnrDb: l.int8.sqnrDb, reason: l.reason,
    })),
  };
}

export function planJsonString(model: Model, a: QuantAnalysis): string {
  return JSON.stringify(planToJson(model, a), null, 2);
}

/** ONNX Runtime static quantization (QDQ) with the plan's exclusions. */
export function ortQuantizeScript(model: Model, a: QuantAnalysis): string {
  const base = baseName(model);
  const { name, shape } = inputInfo(model);
  const excl = a.summary.excluded.map((l) => l.name);
  const perChannel = a.summary.perChannel.length > 0 || a.layers.some((l) => l.recommendation === "int8-per-channel");
  const notOnnx = !/onnx/i.test(model.format);
  return `# Mixed-precision INT8 plan for ${model.name} (generated by ModelVisio).
# ${DISCLAIMER}
# Plan: ${a.summary.counts.int8 + a.summary.counts["int8-per-channel"]} layers INT8, ${excl.length} kept in float.
#
# pip install onnxruntime onnx numpy${notOnnx ? `
#
# NOTE: this model was loaded as ${model.format}. Export it to ONNX first; node
# names below are the layer names ModelVisio saw and may differ after export.` : ""}
import numpy as np
from onnxruntime.quantization import CalibrationDataReader, QuantFormat, QuantType, quantize_static
from onnxruntime.quantization.shape_inference import quant_pre_process

MODEL_FP32 = ${pyStr(base + ".onnx")}
MODEL_PRE = ${pyStr(base + ".pre.onnx")}
MODEL_INT8 = ${pyStr(base + ".int8.onnx")}
INPUT_NAME = ${pyStr(name)}
INPUT_SHAPE = (${shape.join(", ")}${shape.length === 1 ? "," : ""})

# Layers the plan keeps in float (estimated INT8 risk too high).
NODES_TO_EXCLUDE = ${pyList(excl)}


class CalibReader(CalibrationDataReader):
    """Replace the random tensors with ~100-500 real, preprocessed samples."""

    def __init__(self, n=64):
        self.data = iter(
            [{INPUT_NAME: np.random.rand(*INPUT_SHAPE).astype(np.float32)} for _ in range(n)]
        )

    def get_next(self):
        return next(self.data, None)


quant_pre_process(MODEL_FP32, MODEL_PRE)
quantize_static(
    MODEL_PRE,
    MODEL_INT8,
    CalibReader(),
    quant_format=QuantFormat.QDQ,
    per_channel=${perChannel ? "True" : "False"},
    activation_type=QuantType.QUInt8,
    weight_type=QuantType.QInt8,
    nodes_to_exclude=NODES_TO_EXCLUDE,
)
print("wrote", MODEL_INT8)
`;
}

/** TFLite selective quantization via the Quantization Debugger. */
export function tfliteQuantizeScript(model: Model, a: QuantAnalysis): string {
  const base = baseName(model);
  const { shape } = inputInfo(model);
  const tensorOf = new Map(model.layers.map((l) => [l.id, l.outs[0]?.n || l.name]));
  const deny = a.summary.excluded.map((l) => tensorOf.get(l.id) ?? l.name);
  const nchw = shape.length === 4 && shape[1] <= 4 && shape[2] > 4;
  const nhwc = nchw ? [shape[0], shape[2], shape[3], shape[1]] : shape;
  return `# Selective INT8 quantization for ${model.name} (generated by ModelVisio).
# ${DISCLAIMER}
# denylisted_nodes takes op OUTPUT tensor names in the converted TFLite graph.
# The names below are the output tensors ModelVisio saw${/tflite/i.test(model.format) ? "" : ` in the ${model.format} model;
# check them against the converted graph (e.g. in ModelVisio or Netron)`}.
#
# pip install tensorflow numpy
import numpy as np
import tensorflow as tf

SAVED_MODEL_DIR = "saved_model"  # or use TFLiteConverter.from_keras_model(model)
OUTPUT = ${pyStr(base + ".mixed_int8.tflite")}
INPUT_SHAPE = (${nhwc.join(", ")}${nhwc.length === 1 ? "," : ""})${nchw ? "  # NHWC (TFLite layout)" : ""}

# Layers the plan keeps in float (estimated INT8 risk too high).
DENYLISTED_NODES = ${pyList(deny)}


def representative_dataset():
    # Replace with ~100-500 real, preprocessed samples.
    for _ in range(100):
        yield [np.random.rand(*INPUT_SHAPE).astype(np.float32)]


converter = tf.lite.TFLiteConverter.from_saved_model(SAVED_MODEL_DIR)
converter.optimizations = [tf.lite.Optimize.DEFAULT]
converter.representative_dataset = representative_dataset

debugger = tf.lite.experimental.QuantizationDebugger(
    converter=converter,
    debug_dataset=representative_dataset,
    debug_options=tf.lite.experimental.QuantizationDebugOptions(denylisted_nodes=DENYLISTED_NODES),
)
with open(OUTPUT, "wb") as f:
    f.write(debugger.get_nondebug_quantized_model())
print("wrote", OUTPUT)
`;
}

/** One-line human summary of a recommendation count map. */
export function planHeadline(a: QuantAnalysis): string {
  const c = a.summary.counts;
  return (Object.keys(c) as (keyof typeof c)[])
    .filter((k) => c[k] > 0)
    .map((k) => `${c[k]} ${REC_LABEL[k]}`)
    .join(" · ");
}
